    def sign_ownership_override(self, tx_id: str, approver_id: int, rationale: str) -> dict:
        tx = next((t for t in self.transactions if t["tx_id"] == tx_id), None)
        if not tx:
            return {"ok": False, "reason": "Transaction not found"}
        if tx["status"] != "SUSPENDED_REQUIRE_OVERRIDE":
            return {"ok": False, "reason": f"Transaction status is {tx['status']}, not SUSPENDED_REQUIRE_OVERRIDE"}
        exec_info = self.executives.get(approver_id)
        if not exec_info:
            return {"ok": False, "reason": "Unknown approver ID"}

        creator_id = tx["creator_id"]
        role_tier = exec_info["role_tier"]
        deficit_bps = tx["deficit_bps"]
        liability_cents = tx["breach_liability_cents"]
        quota_cents = exec_info["remaining_quota_cents"]

        if creator_id == approver_id:
            return {
                "ok": False,
                "theorem_violated": "ownership_sod_rejects_self_approval",
                "reason": "Separation of Duties (SoD) violation: Creator cannot approve their own order.",
            }

        max_bps = ROLE_MAX_OVERRIDE_BPS.get(role_tier, 0)
        if deficit_bps > max_bps:
            return {
                "ok": False,
                "theorem_violated": "ownership_tier_escalation_sound",
                "reason": f"Role authority insufficient: {ROLE_NAMES.get(role_tier)} max is {max_bps} bps, breach is {deficit_bps} bps.",
            }

        if liability_cents > quota_cents:
            return {
                "ok": False,
                "theorem_violated": "ownership_liability_ledger_conservation",
                "reason": f"Insufficient personal risk quota: required ${liability_cents/100:,.2f}, remaining ${quota_cents/100:,.2f}.",
            }

        ep = self._dispatch_64b_state(
            tx["order_amount_cents"], tx["procure_drift_bps"], tx["mfg_scrap_bps"],
            tx["sales_rebate_bps"], tx["global_slack_budget_bps"],
            creator_id, approver_id, quota_cents
        )

        before_sum = exec_info["remaining_quota_cents"] + exec_info["attributed_liability_cents"]
        exec_info["remaining_quota_cents"] -= liability_cents
        exec_info["attributed_liability_cents"] += liability_cents
        after_sum = exec_info["remaining_quota_cents"] + exec_info["attributed_liability_cents"]
        assert before_sum == after_sum, "Ownership liability conservation invariant violated!"

        sig_payload = f"{tx_id}|{creator_id}|{approver_id}|{deficit_bps}|{liability_cents}|{rationale}|{ep}"
        sig_hash = hashlib.sha256(sig_payload.encode("utf-8")).hexdigest()[:24]

        receipt = {
            "tx_id": tx_id,
            "approver_id": approver_id,
            "approver_name": exec_info["name"],
            "role_name": ROLE_NAMES[role_tier],
            "deficit_bps": deficit_bps,
            "attributed_liability_cents": liability_cents,
            "rationale": rationale,
            "qsbr_epoch": ep,
            "signature_hash": f"0x{sig_hash}",
            "timestamp": int(time.time()),
        }
        tx["status"] = "OVERRIDDEN_APPROVED"
        tx["override_receipt"] = receipt
        self.override_audit_log.insert(0, receipt)
        return {"ok": True, "receipt": receipt, "executive": exec_info}

